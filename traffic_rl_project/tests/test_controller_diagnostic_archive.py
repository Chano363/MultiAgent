def test_exported_native_release_state_reproduces_uninterrupted_physics(tmp_path, monkeypatch):
    import pickle
    from src.controllers.multi_loco_controller import MultiLocoController
    from src.environments.train_fleet_env import TrainFleetEnv
    from src.evaluation.release_feasibility import evaluate_native_release
    output, complete = tmp_path / 'state', tmp_path / 'complete'
    config_args = ['--config', 'configs/experiments/single_10kt108_coupler_rulecal.yaml']
    monkeypatch.setattr(sys, 'argv', ['diagnostic', '--output', str(output),
        '--steps', '3', '--speed', '70', '--save-native-release-state'] + config_args)
    main()
    manifest = json.loads((output / 'native_release_state.json').read_text())
    payload = (output / 'native_release_state.pkl').read_bytes()
    assert hashlib.sha256(payload).hexdigest() == manifest['sha256']
    # Only deserialize the artifact just generated by this test, never user files.
    saved = pickle.loads(payload)
    ctrl = MultiLocoController.__new__(MultiLocoController)
    ctrl.__dict__.update(saved['controller_state'])
    assert ctrl._ab_step == 3
    assert saved['train_env'].dynamics.time == pytest.approx(0.3)
    try:
        branch = evaluate_native_release(saved['train_env'], ctrl, saved['controls'],
            0.3, singleton_leader_offset_mps=TrainFleetEnv.LEAD_TAIL_OFFSET_MPS)
    finally:
        saved['train_env'].close()
    monkeypatch.setattr(sys, 'argv', ['diagnostic', '--output', str(complete),
                                    '--steps', '6', '--speed', '70'] + config_args)
    main()
    with np.load(complete / 'trajectory.npz') as a:
        np.testing.assert_array_equal(branch['trajectory'][:,1],
            np.abs(a['coupler_interface_force_n'][3:]).reshape(3,-1).max(1))
        np.testing.assert_array_equal(branch['trajectory'][:,2],
            a['vehicle_speeds_mps'][3:].reshape(3,-1).max(1))
    from src.evaluation.continue_native_release_control import main as continue_main
    continued = tmp_path / 'continued'
    # The continuation loader deliberately accepts only our validation archive.
    # Use a test workspace symlink-free copy below the test's allowed root.
    import shutil
    trusted = tmp_path / 'outputs/sim_validation/phys_validation/state'
    trusted.parent.mkdir(parents=True)
    shutil.copytree(output, trusted)
    monkeypatch.setattr('src.evaluation.continue_native_release_control.native_source_hashes',
                        lambda: manifest['native_source_sha256'])
    monkeypatch.chdir(tmp_path)
    monkeypatch.setattr(sys, 'argv', ['continuation', '--state-dir', str(trusted),
        '--controller-source', str(trusted / 'controller_source.py'),
        '--output', str(continued), '--steps', '3', '--save-native-release-state'])
    continue_main()
    continuation_manifest = json.loads((continued / 'native_release_state.json').read_text())
    assert continuation_manifest['elapsed_s'] == pytest.approx(0.6)
    assert continuation_manifest['origin_native_manifest']['sha256'] == manifest['sha256']
    assert hashlib.sha256((continued / 'native_release_state.pkl').read_bytes()).hexdigest() == continuation_manifest['sha256']
    with np.load(complete / 'trajectory.npz') as a, np.load(continued / 'trajectory.npz') as b:
        for key in ('vehicle_positions_m', 'vehicle_speeds_mps',
                    'coupler_interface_force_n', 'effective_pressure_coefficient',
                    'physical_loco_ed'):
            np.testing.assert_array_equal(a[key][3:, 0], b[key])


def test_requested_stop_preserves_complete_steps_and_reason_on_reuse(tmp_path, monkeypatch):
    output, stop = tmp_path / 'trace', tmp_path / 'stop'
    stop.touch()
    args = ['diagnostic', '--output', str(output), '--steps', '8', '--speed', '70',
            '--stop-file', str(stop)]
    monkeypatch.setattr(sys, 'argv', args)
    main()
    record = json.loads((output / 'result.json').read_text(encoding='utf-8'))
    assert record['summary']['steps'] == 3
    assert record['summary']['diagnostic_stop_reason'] == 'requested_stop_file'
    assert not record['summary']['full_route_completed']
    with np.load(output / 'trajectory.npz') as saved:
        assert len(saved['rows']) == len(saved['commands']) == 3
        assert saved['vehicle_speeds_mps'].shape[0] == 3
        original = saved['vehicle_speeds_mps'].copy()
    monkeypatch.setattr(sys, 'argv', args + ['--reuse'])
    main()
    replay = json.loads((output / 'result.json').read_text(encoding='utf-8'))
    assert replay['summary']['diagnostic_stop_reason'] == 'requested_stop_file'
    with np.load(output / 'trajectory.npz') as saved:
        np.testing.assert_array_equal(saved['vehicle_speeds_mps'], original)
    uninterrupted = tmp_path / 'uninterrupted'
    monkeypatch.setattr(sys, 'argv', ['diagnostic', '--output', str(uninterrupted),
                                    '--steps', '8', '--speed', '70'])
    main()
    with np.load(output / 'trajectory.npz') as partial, np.load(
            uninterrupted / 'trajectory.npz') as complete:
        for key in ('vehicle_speeds_mps', 'coupler_interface_force_n', 'commands',
                    'effective_pressure_coefficient', 'physical_loco_ed'):
            np.testing.assert_array_equal(partial[key], complete[key][:3])


