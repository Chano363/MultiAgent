const FONT_BODY = { ascii: "Times New Roman", hAnsi: "Times New Roman", eastAsia: "SimSun" };
const FONT_HEAD = { ascii: "Arial", hAnsi: "Arial", eastAsia: "SimHei" };

function pagePara(label, text) {
  return new Paragraph({
    children: [
      new TextRun({ text: label, font: FONT_BODY, size: 24, bold: true }),
      new TextRun({ text, font: FONT_BODY, size: 24 }),
    ],
    spacing: { line: 360, lineRule: "auto", after: 120 },
    alignment: AlignmentType.JUSTIFIED,
  });
}

function h1(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_1,
    children: [new TextRun({ text, font: FONT_HEAD, size: 32, bold: true, color: "000000" })],
    spacing: { before: 240, after: 240 },
    alignment: AlignmentType.CENTER,
  });
}

function h2(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_2,
    children: [new TextRun({ text, font: FONT_HEAD, size: 28, bold: true, color: "000000" })],
    spacing: { before: 240, after: 180 },
  });
}

function boldLead(lead, rest) {
  return new Paragraph({
    children: [
      new TextRun({ text: lead, font: FONT_BODY, size: 24, bold: true }),
      new TextRun({ text: rest, font: FONT_BODY, size: 24 }),
    ],
    spacing: { line: 360, lineRule: "auto", after: 120 },
    alignment: AlignmentType.JUSTIFIED,
  });
}

