# 摩擦系数（论文式6）
def friction_coef(P_sh, v):
    """φ = 0.41*(P_sh+150)/(4*P_sh+200) * (v+150)/(2v+150), P_sh 单位 kPa"""
    return 0.41 * (P_sh + 150.0) / (4.0 * P_sh + 200.0) * (v + 150.0) / (2.0 * v + 150.0)

def shoe_pressure(P_cyl, br, nsh):
    """论文式7: 单块闸瓦压力 P_sh = (π/4) dZ^2 nZ ηZ ψZ P_i * 1e-6 / nsh  (kPa·m^2 = kN)"""
    return (np.pi / 4.0 * br["dZ"] ** 2 * br["nZ"] * br["etaZ"] * br["psiZ"]
            * P_cyl * 1e-6 / nsh)

# ----------------------------------------------------------------------
# 运行阻力（论文式9 戴维斯公式）
# 单位约定：w0 [kN/t]，F_W0 = m[t] * w0 [kN]。
# 系数按 w0 = c0 + c1 v + c2 v^2 解读为 kN/t（等价于 N/kg），
# 80 km/h 时约 16 N/t，量级合理。
# ----------------------------------------------------------------------
C0 = 0.0063           # [T3]
C1 = 1.08e-4          # [T3]
C2 = 1.4918e-5        # [T3]

def davis_w0(v):
    return C0 + C1 * v + C2 * v * v   # kN/t

